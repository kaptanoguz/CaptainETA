import pickle, json, os
from load import PORTS, COORDS

DROP = {"Jeddah (Islamic Port), Saudi Arabia", "Jebel Ali (Dubai Port), UAE", "Mumbai (JNPT), India"}
RENAME = {"Nhava Sheva, India": "Nhava Sheva (JNPT), India"}
V = pickle.load(open('variants.pkl', 'rb'))
names = [p for p in PORTS if p not in DROP]
out_names = [RENAME.get(p, p) for p in names]
n = len(names)

def d(var, a, b):
    k = tuple(sorted((a, b)))
    return V[var][0][k]

base = []
for i in range(n):
    for j in range(i + 1, n):
        base.append(int(round(d('base', names[i], names[j]))))

deltas = {}

def idx(i, j):  # upper-triangle index, i < j
    return i * n - i * (i + 1) // 2 + (j - i - 1)

for var in ('kiel', 'cape', 'kiel_cape'):
    dv = {}
    for i in range(n):
        for j in range(i + 1, n):
            k = idx(i, j)
            v = int(round(d(var, names[i], names[j])))
            # kiel_cape only stores what cannot be inferred from the single options (see getDist)
            ref = base[k] if var != 'kiel_cape' else deltas['cape'].get(k, deltas['kiel'].get(k, base[k]))
            if abs(v - ref) >= 2: dv[k] = v
    deltas[var] = dv
    print(var, len(dv), 'pairs stored')

coords = {RENAME.get(p, p): COORDS[p] for p in names}
js = f"""// Captain ETA port database — generated by the distance builder, do not edit by hand.
//
// Distances are sea-route distances in nautical miles, berth to berth (approx.):
//  - regional legs: shortest path on a 1-arc-minute Mercator grid built from Natural Earth 10m
//    coastlines and NOAA ETOPO1 bathymetry (water shallower than 10 m is avoided), with narrow
//    straits, canals and river approaches opened explicitly, then smoothed to any-angle lines;
//  - long-haul legs: European ports are joined through ocean gateways (Gibraltar, Ushant,
//    Red Sea, North Scotland) to the Eurostat MARNET network (searoute).
// Validated against NGA Pub. 151 "Distances Between Ports": median deviation about 1 %.
//
// SEA_DIST holds the default (deep-draft) routing: no Kiel Canal, Oresund closed, Suez open.
// ROUTE_ALT holds only the pairs that change under the optional routings.

const PORTS = {json.dumps(out_names, ensure_ascii=False)};

const PORT_COORDS = {json.dumps(coords, ensure_ascii=False, separators=(',', ':'))};

const SEA_DIST = [{','.join(map(str, base))}];

const ROUTE_ALT = {{
{chr(10).join(f"  {k}: {{" + ','.join(f'{i}:{v}' for i, v in dv.items()) + "}," for k, dv in deltas.items())}
}};

const PORT_INDEX = Object.fromEntries(PORTS.map((p, i) => [p, i]));

// opts: {{ kiel: bool, cape: bool }}  -> distance in nm, or null if either port is unknown
function getDist(a, b, opts = {{}}){{
  let i = PORT_INDEX[a], j = PORT_INDEX[b];
  if (i === undefined || j === undefined || i === j) return null;
  if (i > j) [i, j] = [j, i];
  const n = PORTS.length, k = i * n - i * (i + 1) / 2 + (j - i - 1);
  const A = ROUTE_ALT;
  if (opts.kiel && opts.cape) return A.kiel_cape[k] ?? A.cape[k] ?? A.kiel[k] ?? SEA_DIST[k];
  if (opts.cape) return A.cape[k] ?? SEA_DIST[k];
  if (opts.kiel) return A.kiel[k] ?? SEA_DIST[k];
  return SEA_DIST[k];
}}
"""
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'ports.js'), 'w', encoding='utf-8').write(js)
print(n, 'ports,', len(js) // 1024, 'KB')
